#!/usr/bin/env python3
"""
Universal Application Theme Synchronizer for Quickshell
Synchronizes active theme palette to:
1. GTK4 / Libadwaita (Nautilus, Loupe, GNOME Music, GNOME Camera, GNOME Calculator)
2. Ghostty terminal emulator
3. VSCodium
4. Zen Browser
"""

import sys
import os
import json
import glob
import subprocess
from pathlib import Path

HOME = Path.home()
CONFIG_DIR = HOME / ".config" / "quickshell"
PALETTES_FILE = CONFIG_DIR / "theme" / "palettes.json"

def load_palettes():
    if not PALETTES_FILE.exists():
        print(f"Error: Palettes file {PALETTES_FILE} does not exist.")
        sys.exit(1)
    with open(PALETTES_FILE, "r") as f:
        return json.load(f)

