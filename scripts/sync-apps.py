        with open(user_chrome_file, "w") as f:
            f.write(theme_css)

        # Ensure user.js has stylesheet preference enabled
        pref_line = 'user_pref("toolkit.legacyUserProfileCustomizations.stylesheets", true);\n'
        if not user_js_file.exists():
            with open(user_js_file, "w") as f:
                f.write(pref_line)
